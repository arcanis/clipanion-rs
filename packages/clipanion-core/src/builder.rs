#[derive(Clone, Debug, Default, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "camelCase"))]
#[cfg_attr(feature = "serde", derive(ts_rs::TS))]
#[cfg_attr(feature = "serde", ts(export, export_to = "index.ts"))]
pub struct CommandSpec {
    pub primary_path: List<Str>,
    pub aliases: List<List<Str>>,
    pub category: Option<Str>,
    pub documentation: Option<Documentation>,
    pub examples: List<Example>,
    pub components: List<Component>,
    pub required_options: List<usize>,
}

impl std::fmt::Display for CommandSpec {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let (prefix_components, suffix_components): (Vec<_>, _)
            = self.components.iter()
                .filter(|component| !matches!(component, Component::Option(OptionSpec {is_hidden: true, ..})))
                .partition(|component| matches!(component, Component::Positional(PositionalSpec::Dynamic {is_prefix: true, ..})));

        let components
            = prefix_components.into_iter()
                .map(|component| component.to_string())
                .chain(self.primary_path.iter().map(|segment| segment.to_string()))
                .chain(suffix_components.into_iter().map(|component| component.to_string()));

        format_collection(f, components, " ")?;

        Ok(())
    }
}

impl CommandSpec {
    pub fn is_default(&self) -> bool {
        self.primary_path.is_empty() || self.aliases.iter().any(|path| path.is_empty())
    }

    /// The command's paths: its primary path, then its aliases.
    pub fn paths(&self) -> impl Iterator<Item = &[Str]> {
        once(&*self.primary_path)
            .chain(self.aliases.iter().map(|path| &**path))
    }

    pub fn usage(&self) -> CommandUsageResult<'_> {
        CommandUsageResult::new(self)
    }

    pub fn build(&'_ self, command_id: usize) -> CliMachine<'_> {
        CommandBuilderContext::new(self, command_id).build()
    }
}

pub struct CommandBuilderContext<'cmds> {
    machine: CliMachine<'cmds>,
    spec: &'cmds CommandSpec,

    /// Whether we're building a proxy, which takes every word: no options.
    proxy: bool,

    /// Whether that proxy only starts at a word that isn't option-like.
    proxy_program: bool,

    /// Whether `-h` and `--help` asked for help where options were last attached.
    help: bool,
}

impl<'cmds> CommandBuilderContext<'cmds> {
    fn new(spec: &'cmds CommandSpec, command_id: usize) -> Self {
        CommandBuilderContext {
            machine: CliMachine::new(command_id),
            spec,
            proxy: false,
            proxy_program: false,
            help: true,
        }
    }

    /// Lets the command's options be given on `node_id`: the runner reads them
    /// there, from the command's spec, and stays on the node.
    fn attach_options(&mut self, node_id: usize, is_followed_by_proxy: bool) -> usize {
        if !self.proxy {
            // A proxy that directly follows the command's path takes `-h` and `--help`.
            self.help = !is_followed_by_proxy;

            self.machine.nodes[node_id].options = Some(NodeOptions {
                help: self.help,
            });
        }

        node_id
    }

    fn positional_check(&self, reducer: &Reducer) -> Option<Check> {
        match (self.proxy, reducer) {
            (false, _) => Some(Check::IsPositional),

            // Until a proxy starts, the command's options are read as options;
            // with `proxy_program`, any option-like word is.
            (true, Reducer::StartPositional(_)) => match self.proxy_program {
                true => Some(Check::IsPositional),
                false => Some(Check::IsProxyStart {help: self.help}),
            },

            (true, _) => None,
        }
    }

    fn attach_required(&mut self, pre_node_id: usize, reducer: Reducer) -> usize {
        let next_node_id
            = self.machine.create_node();

        self.machine.register_dynamic(
            pre_node_id,
            self.positional_check(&reducer),
            next_node_id,
            Some(reducer),
        );

        self.attach_options(next_node_id, false)
    }

    fn attach_variadic(&mut self, pre_node_id: usize, min_len: usize, extra_len: Option<usize>, start_action: Reducer, subsequent_actions: Reducer) -> usize {
        let mut current_node_id
            = pre_node_id;

        let mut next_action
            = start_action.clone();

        for _ in 0..min_len {
            current_node_id = self.attach_required(current_node_id, next_action);
            next_action = subsequent_actions.clone();
        }

        match extra_len {
            Some(extra_len) => {
                if extra_len > 0 {
                    let end_node_id
                        = self.machine.create_node();

                    self.machine.register_shortcut(
                        current_node_id,
                        end_node_id,
                    );

                    for _ in 0..extra_len {
                        current_node_id = self.attach_required(current_node_id, next_action);
                        next_action = subsequent_actions.clone();

                        self.machine.register_shortcut(
                            current_node_id,
                            end_node_id,
                        );
                    }

                    current_node_id = end_node_id;
                }
            },

            None => {
                let end_node_id
                    = self.machine.create_node();

                self.machine.register_shortcut(
                    current_node_id,
                    end_node_id,
                );

                if next_action == start_action && next_action != subsequent_actions {
                    current_node_id = self.attach_required(current_node_id, next_action);
                    next_action = subsequent_actions;

                    self.machine.register_shortcut(
                        current_node_id,
                        end_node_id,
                    );
                }

                let post_variadic_node_id
                    = self.attach_required(current_node_id, next_action);

                self.machine.register_shortcut(
                    post_variadic_node_id,
                    current_node_id,
                );

                current_node_id = end_node_id;
            },
        }

        current_node_id
    }

    fn attach_positionals(&mut self, pre_node_id: usize, positionals: &Vec<(usize, &'cmds PositionalSpec)>) -> usize {
        let mut current_node_id
            = pre_node_id;

        for (id, spec) in positionals {
            match spec {
                PositionalSpec::Keyword {expected} => {
                    let next_node_id
                        = self.machine.create_node();

                    self.machine.register_static(
                        current_node_id,
                        ArgKey::User(expected),
                        next_node_id,
                        Some(Reducer::IncreaseStaticCount),
                    );

                    current_node_id
                        = self.attach_options(next_node_id, false);
                },

                PositionalSpec::Dynamic {min_len, extra_len, is_proxy, proxy_program, ..} => {
                    self.proxy = *is_proxy;
                    self.proxy_program = *is_proxy && *proxy_program;

                    current_node_id = self.attach_variadic(
                        current_node_id,
                        *min_len,
                        *extra_len,
                        Reducer::StartPositional(*id),
                        Reducer::PushPositional,
                    );

                    self.proxy = false;
                    self.proxy_program = false;
                },
            }
        }

        current_node_id
    }

    fn build(mut self) -> CliMachine<'cmds> {
        let first_node_id
            = self.machine.create_node();

        self.machine.register_static(
            INITIAL_NODE_ID,
            ArgKey::StartOfInput,
            first_node_id,
            None,
        );

        // A proxy that directly follows the path takes `-h` and `--help`, unless it
        // only starts at a word that isn't option-like.
        let is_first_positional_a_help_proxy
            = self.spec.components.iter()
                .find_map(|component| if let Component::Positional(PositionalSpec::Dynamic {is_prefix, is_proxy, proxy_program, ..}) = component {(!is_prefix).then_some(*is_proxy && !*proxy_program)} else {None})
                .unwrap_or(false);

        let mut current_node_id
            = self.attach_options(first_node_id, false);

        let positional_components = self.spec.components.iter()
            .enumerate()
            .filter_map(|(i, component)| if let Component::Positional(spec) = component {Some((i, spec))} else {None})
            .collect::<Vec<_>>();

        let (prefix_components, positional_components)
            = positional_components.into_iter()
                .partition(|(_, spec)| matches!(spec, PositionalSpec::Dynamic {is_prefix: true, ..}));

        current_node_id
            = self.attach_positionals(current_node_id, &prefix_components);

        let paths
            = self.spec.aliases.iter()
                .chain(once(&self.spec.primary_path))
                .collect::<Vec<_>>();

        if !paths.is_empty() && !paths.iter().all(|path| path.is_empty()) {
            let post_paths_node_id
                = self.machine.create_node();

            for path in &paths {
                let mut current_path_node_id
                    = current_node_id;

                if !path.is_empty() {
                    for (i, segment) in path.iter().enumerate() {
                        let is_last_segment
                            = i == path.len() - 1;
                        let is_followed_by_proxy
                            = is_last_segment && is_first_positional_a_help_proxy;

                        let post_segment_node_id
                            = self.machine.create_node();

                        self.machine.register_static(
                            current_path_node_id,
                            ArgKey::User(segment),
                            post_segment_node_id,
                            Some(Reducer::IncreaseStaticCount),
                        );

                        current_path_node_id
                            = self.attach_options(post_segment_node_id, is_followed_by_proxy);
                    }
                }

                self.machine.register_shortcut(
                    current_path_node_id,
                    post_paths_node_id,
                );
            }

            current_node_id = post_paths_node_id;
        }

        current_node_id
            = self.attach_positionals(current_node_id, &positional_components);

        self.machine.register_static(
            current_node_id,
            ArgKey::EndOfInput,
            SUCCESS_NODE_ID,
            None,
        );

        self.machine
    }
}

#[derive(Clone)]
pub struct CliBuilder<'cmds> {
    commands: Vec<&'cmds CommandSpec>,
}

impl<'cmds> CliBuilder<'cmds> {
    pub fn new() -> Self {
        CliBuilder {
            commands: vec![],
        }
    }

    pub fn add_command(&mut self, spec: &'cmds CommandSpec) -> &mut Self {
        self.commands.push(spec);
        self
    }

    pub fn compile(&self) -> CliMachine<'cmds> {
        let command_machines
            = self.commands.iter()
                .enumerate()
                .map(|(command_id, &command)| command.build(command_id));

        let mut machine
            = CliMachine::new_any_of(command_machines);

        machine.simplify_machine();
        machine
    }

    pub fn run_partial<'args>(&self, args: &[&'args str]) -> Vec<State<'args>> {
        let machine
            = self.compile();

        Runner::run_partial(&machine, &self.commands, args)
    }

    pub fn run<'a, 'args>(&'a self, args: &'a [&'args str]) -> Result<Selector<'a, 'cmds, 'args>, Error<'cmds>> {
        let machine
            = self.compile();

        let states
            = Runner::run(&machine, &self.commands, args);

        Ok(Selector::new(&self.commands, args, states))
    }
}

