#[derive(Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "camelCase"))]
#[cfg_attr(feature = "serde", derive(ts_rs::TS))]
#[cfg_attr(feature = "serde", ts(export_to = "index.ts"))]
pub struct OptionSpec {
    pub primary_name: Str,
    pub aliases: List<Str>,

    pub documentation: Option<Documentation>,
    pub default_value: Option<Str>,

    pub min_len: usize,
    pub extra_len: Option<usize>,

    pub allow_binding: bool,
    pub allow_boolean: bool,
    pub is_hidden: bool,
    pub is_required: bool,
}

impl OptionSpec {
    fn parse_names(name: &str) -> (Str, List<Str>) {
        let names = name
            .split(',')
            .collect::<Vec<_>>();

        let (primary_name, aliases) = names
            .split_first()
            .unwrap();

        let aliases = aliases.iter()
            .map(|name| Cow::Owned(name.to_string()))
            .collect::<Vec<_>>();

        (Cow::Owned(primary_name.to_string()), aliases.into())
    }

    pub fn boolean(name: &str) -> Self {
        let (primary_name, aliases)
            = Self::parse_names(name);

        OptionSpec {
            primary_name,
            aliases,

            documentation: None,
            default_value: None,

            min_len: 0,
            extra_len: Some(0),

            allow_binding: false,
            allow_boolean: true,
            is_hidden: false,
            is_required: false,
        }
    }

    pub fn parametrized(name: &str) -> Self {
        let (primary_name, aliases)
            = Self::parse_names(name);

        OptionSpec {
            primary_name,
            aliases,

            documentation: None,
            default_value: None,

            min_len: 1,
            extra_len: Some(0),

            allow_binding: false,
            allow_boolean: false,
            is_hidden: false,
            is_required: true,
        }
    }

    pub fn primary_name(&self) -> &str {
        &self.primary_name
    }

    pub fn all_names(&self) -> impl Iterator<Item = &str> {
        once(self.primary_name())
            .chain(self.aliases.iter().map(|alias| &**alias))
    }
}

impl std::fmt::Display for OptionSpec {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        if self.is_required {
            write!(f, "<{}", self.primary_name)?;
        } else {
            write!(f, "[{}", self.primary_name)?;
        }

        for alias in self.aliases.iter() {
            write!(f, ",{}", alias)?;
        }

        if self.min_len > 0 || self.extra_len != Some(0) {
            write!(f, " ")?;
            format_range(f, "arg", self.min_len, self.extra_len)?;
        }

        if self.is_required {
            write!(f, ">")
        } else {
            write!(f, "]")
        }
    }
}

